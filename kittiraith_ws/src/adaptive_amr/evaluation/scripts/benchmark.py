#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
benchmark.py — offline KITTI benchmark runner.

Computes the quantitative metrics for the stack's modules:

    --odom  estimated odometry poses  (NPZ or 12-float-per-line text)
            -> ATE + RPE vs KITTI odometry ground truth
    --track predicted tracks (NPZ)     -> MOTA/MOTP vs KITTI tracking GT
    --seg   predicted label image      -> mIoU vs GT label image
    --grid  predicted grid (NPZ)       -> precision/recall vs GT grid

Output: markdown report (+ optional CSV) written to evaluation/report/.

Example:
    python3 evaluation/scripts/benchmark.py \
        --odom est_poses.npz --gt-odom-root /data/kitti/odometry \
        --seq 05 --report evaluation/report/benchmark.md

Estimate file formats:
    NPZ:   {"poses": (N,4,4)}   or text: N lines of 12 floats (R|t).
    Tracks NPZ: {"boxes": (T,), "ids": (T,)} arrays of per-frame lists.
"""

import argparse
import json
import os
import sys
from typing import Dict, List

import numpy as np

# allow running from the package dir without a catkin install
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "src"))

from evaluation.metrics import (absolute_trajectory_error,  # noqa: E402
                                grid_precision_recall, mot_metrics,
                                relative_pose_error, segmentation_iou)


# --------------------------------------------------------------------------- #
# Loaders
# --------------------------------------------------------------------------- #
def load_poses(path: str) -> List[np.ndarray]:
    """Load poses from an .npz (key "poses") or 12-float-per-line text file."""
    if path.endswith(".npz"):
        data = np.load(path)
        if "poses" not in data:
            raise ValueError("npz must contain key 'poses'")
        return [np.asarray(p) for p in data["poses"]]
    poses = []
    with open(path, "r") as handle:
        for line in handle:
            values = [float(tok) for tok in line.split()]
            if len(values) == 12:
                m = np.eye(4)
                m[:3, :] = np.asarray(values).reshape(3, 4)
                poses.append(m)
            elif len(values) == 7:            # tx ty tz qx qy qz qw
                tx, ty, tz, qx, qy, qz, qw = values
                m = np.eye(4)
                m[:3, 3] = [tx, ty, tz]
                m[:3, :3] = _quat_to_matrix(qx, qy, qz, qw)
                poses.append(m)
            elif line.strip():
                raise ValueError("unrecognized pose line: {}".format(line.strip()))
    if not poses:
        raise ValueError("no poses loaded from {}".format(path))
    return poses


def _quat_to_matrix(x, y, z, w):
    return np.array([
        [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
        [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
        [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
    ])


def load_gt_poses(root: str, seq: str) -> List[np.ndarray]:
    from dataset_loader.kitti_parsers import (KittiOdometryPaths,
                                              read_odometry_poses)
    paths = KittiOdometryPaths(root, seq)
    return read_odometry_poses(paths.poses_path)


# --------------------------------------------------------------------------- #
# Report
# --------------------------------------------------------------------------- #
def write_report(path: str, sections: Dict[str, str]) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as handle:
        handle.write("# kittiraith_ws — Benchmark Report\n\n")
        handle.write("Generated by evaluation/scripts/benchmark.py\n\n")
        for title, body in sections.items():
            handle.write("## {}\n\n{}\n\n".format(title, body))


def fmt_metrics(metrics: Dict) -> str:
    lines = []
    for key, value in metrics.items():
        if isinstance(value, float):
            lines.append("| {} | {:.4f} |".format(key, value))
        else:
            lines.append("| {} | {} |".format(key, value))
    return "\n".join(["| metric | value |", "|---|---|"] + lines)


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #
def main(argv=None):
    parser = argparse.ArgumentParser(description="KITTI benchmark runner")
    parser.add_argument("--odom", help="estimated odometry poses (npz/text)")
    parser.add_argument("--gt-odom-root", default="/data/kitti/odometry")
    parser.add_argument("--seq", default="05")
    parser.add_argument("--rpe-lengths", default="100,200",
                        help="comma-separated RPE sub-sequence lengths")
    parser.add_argument("--track", help="predicted tracks npz")
    parser.add_argument("--seg", help="predicted label image npz")
    parser.add_argument("--seg-gt", help="ground-truth label image npz")
    parser.add_argument("--grid", help="predicted grid npz")
    parser.add_argument("--grid-gt", help="ground-truth grid npz")
    parser.add_argument("--report", default="evaluation/report/benchmark.md")
    args = parser.parse_args(argv)

    sections = {}

    # ---- odometry ----------------------------------------------------------
    if args.odom:
        est = load_poses(args.odom)
        gt = load_gt_poses(args.gt_odom_root, args.seq)
        n = min(len(est), len(gt))
        est, gt = est[:n], gt[:n]
        ate = absolute_trajectory_error(est, gt)
        body = fmt_metrics(ate)
        for length in [int(v) for v in args.rpe_lengths.split(",")]:
            rpe = relative_pose_error(est, gt, length)
            body += "\n\n**RPE length {}**\n\n{}".format(length,
                                                        fmt_metrics(rpe))
        sections["Odometry (ATE / RPE) — seq {}".format(args.seq)] = body

    # ---- tracking -----------------------------------------------------------
    if args.track:
        data = np.load(args.track, allow_pickle=True)
        m = mot_metrics(data["gt_boxes"], data["gt_ids"],
                        data["pred_boxes"], data["pred_ids"])
        sections["Tracking (MOTA / MOTP)"] = fmt_metrics(m)

    # ---- segmentation ---------------------------------------------------------
    if args.seg and args.seg_gt:
        pred = np.load(args.seg)["labels"]
        gt = np.load(args.seg_gt)["labels"]
        sections["Segmentation (mIoU)"] = fmt_metrics(segmentation_iou(pred, gt))

    # ---- grid -----------------------------------------------------------------
    if args.grid and args.grid_gt:
        pred = np.load(args.grid)["grid"]
        gt = np.load(args.grid_gt)["grid"]
        sections["Occupancy grid (precision/recall)"] = fmt_metrics(
            grid_precision_recall(pred, gt))

    if not sections:
        parser.error("provide at least one of --odom/--track/--seg/--grid")

    write_report(args.report, sections)
    print("Benchmark report written to {}".format(args.report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
